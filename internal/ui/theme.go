func ThemeByID(id string) Theme {
	for _, t := range Themes() {
		if string(t.ID) == id {
			return t
		}
	}
	return Themes()[0]
}

func ValidTheme(id string) bool {
	for _, t := range Themes() {
		if string(t.ID) == id {
			return true
		}
	}
	return false
}

func applyThemeColors(t Theme) {
	colBG, colWood, colWoodHi = t.BG, t.Wood, t.WoodHi
	colFelt, colFeltDk = t.Felt, t.FeltDk
	colPointL, colPointD = t.PointL, t.PointD
	colWhite, colWhiteLn = t.White, t.WhiteLn
	colBlack, colBlackLn = t.Black, t.BlackLn
	colGold, colGoldDk = t.Gold, t.GoldDk
	colCream, colInk, colMute = t.Cream, t.Ink, t.Mute
	colSelect = t.Select
}

// setTheme switches palette, board kit and layout. Game state is untouched:
// only the geometry used to place and hit-test checkers changes.
func (a *App) setTheme(id ThemeID) {
	t := ThemeByID(string(id))
	a.theme = t
	a.cfg.Theme = string(t.ID)
	applyThemeColors(t)
	a.kit = kitFor(t.ID)
	if a.kit != nil {
		a.layout = a.kit.layout()
	} else {
		a.layout = newLayout()
	}
}
